/**
 * Kiosk state machine states (spec §21).
 *
 * Spec states that are instant steps inside one atomic service call
 * (SCANNING_ID, CHECKING_AVAILABILITY, PAYMENT_CONFIRMED, VERIFYING_RFID)
 * don't need their own waiting state. WAITING_FOR_PENALTY_PAYMENT is
 * added for the team's pay-first return policy; SHOWING_MESSAGE holds a
 * refusal/timeout screen before returning to SYSTEM_READY.
 */
export const KioskState = {
  STARTING: 'STARTING',
  WAITING_FOR_CLOCK: 'WAITING_FOR_CLOCK',
  SYSTEM_READY: 'SYSTEM_READY',
  VALIDATING_STUDENT: 'VALIDATING_STUDENT',
  // borrowing
  SELECTING_LOCKER: 'SELECTING_LOCKER', // student picks a locker with its blue button
  WAITING_FOR_PAYMENT: 'WAITING_FOR_PAYMENT',
  OPENING_LOCKER: 'OPENING_LOCKER',
  WAITING_FOR_REMOVAL: 'WAITING_FOR_REMOVAL',
  WAITING_FOR_DOOR_CLOSE: 'WAITING_FOR_DOOR_CLOSE', // calculator taken, waiting for the red button
  RENTAL_ACTIVE: 'RENTAL_ACTIVE',
  // returning
  RETURN_IDENTIFIED: 'RETURN_IDENTIFIED',
  WAITING_FOR_PENALTY_PAYMENT: 'WAITING_FOR_PENALTY_PAYMENT',
  RETURN_OPENING_LOCKER: 'RETURN_OPENING_LOCKER',
  WAITING_FOR_RETURN: 'WAITING_FOR_RETURN',
  RETURN_COMPLETE: 'RETURN_COMPLETE',
  // officers
  OFFICER_UNLOCK: 'OFFICER_UNLOCK', // emergency unlock from the dashboard (Phase 13)
  // power management
  SLEEPING: 'SLEEPING', // idle: LCD backlight, camera and RFID readers off until a button is pressed
  // messages & faults
  SHOWING_MESSAGE: 'SHOWING_MESSAGE',
  ERROR: 'ERROR',
} as const;
export type KioskState = (typeof KioskState)[keyof typeof KioskState];

const S = KioskState;

/** Only these moves are allowed (e.g. never SYSTEM_READY → OPENING_LOCKER). ERROR is reachable from anywhere. */
export const KIOSK_TRANSITIONS: Readonly<Record<KioskState, readonly KioskState[]>> = {
  [S.STARTING]: [S.WAITING_FOR_CLOCK, S.SYSTEM_READY],
  [S.WAITING_FOR_CLOCK]: [S.SYSTEM_READY],
  [S.SYSTEM_READY]: [S.VALIDATING_STUDENT, S.OFFICER_UNLOCK, S.SLEEPING],
  [S.OFFICER_UNLOCK]: [S.SYSTEM_READY],
  [S.SLEEPING]: [S.SYSTEM_READY],
  [S.VALIDATING_STUDENT]: [S.SELECTING_LOCKER, S.RETURN_IDENTIFIED, S.SHOWING_MESSAGE],
  [S.SELECTING_LOCKER]: [S.WAITING_FOR_PAYMENT, S.SHOWING_MESSAGE],
  [S.WAITING_FOR_PAYMENT]: [S.OPENING_LOCKER, S.SHOWING_MESSAGE],
  [S.OPENING_LOCKER]: [S.WAITING_FOR_REMOVAL],
  [S.WAITING_FOR_REMOVAL]: [S.WAITING_FOR_DOOR_CLOSE, S.SHOWING_MESSAGE],
  [S.WAITING_FOR_DOOR_CLOSE]: [S.RENTAL_ACTIVE, S.SHOWING_MESSAGE],
  [S.RENTAL_ACTIVE]: [S.SYSTEM_READY],
  [S.RETURN_IDENTIFIED]: [S.WAITING_FOR_PENALTY_PAYMENT, S.RETURN_OPENING_LOCKER],
  [S.WAITING_FOR_PENALTY_PAYMENT]: [S.RETURN_OPENING_LOCKER, S.SHOWING_MESSAGE],
  [S.RETURN_OPENING_LOCKER]: [S.WAITING_FOR_RETURN],
  [S.WAITING_FOR_RETURN]: [S.RETURN_COMPLETE, S.SHOWING_MESSAGE],
  [S.RETURN_COMPLETE]: [S.SYSTEM_READY],
  [S.SHOWING_MESSAGE]: [S.SYSTEM_READY],
  [S.ERROR]: [S.SYSTEM_READY],
};

export function canMove(from: KioskState, to: KioskState): boolean {
  return to === S.ERROR || KIOSK_TRANSITIONS[from].includes(to);
}
